'use strict';
const assert=require('node:assert/strict');
const J=require('../v5/duel-journey-lab.js');
const D=require('../v5/duel-invitations-lab.js');
const context={currentStage:3,duelsEnabled:true};
const peer=k=>({view:{rosterKey:'trial-'+k,progress:{currentStage:3,awaitingPeers:true},duel:{eligible:true,mission:3}},roomKey:'trial-room-life',online:true});
const from=peer('ana'),to=peer('bia');
let s=J.create();
assert.equal(s.phase,'mission');
assert(Object.isFrozen(s));
assert.throws(()=>J.advance(s,'finish',{mode:'3d',winner:'trial-ana',seconds:1,players:['trial-ana','trial-bia']}),/transição inválida/);
assert.throws(()=>J.advance(s,'invite',{invitationId:0}),/convite fictício/);
s=J.advance(s,'invite',{invitationId:1});assert.equal(s.phase,'invited');
assert.throws(()=>J.advance(s,'enter'),/transição inválida/);
const declined=J.advance(s,'decline');assert.equal(declined.phase,'declined');
assert.equal(J.advance(declined,'invite',{invitationId:2}).phase,'invited');
s=J.advance(s,'accept');assert.equal(s.phase,'accepted');
assert.throws(()=>J.advance(s,'ready'),/transição inválida/);
s=J.advance(s,'enter');assert.equal(s.phase,'entering');
s=J.advance(s,'leave');assert.equal(s.phase,'accepted','close prior to result permits reopening without granting XP');
s=J.advance(s,'enter');
s=J.advance(s,'ready');assert.equal(s.phase,'fighting');
assert.throws(()=>J.advance(s,'finish',{mode:'3d',winner:'trial-unknown',seconds:3,players:['trial-ana','trial-bia']}),/vencedor fora/);
assert.throws(()=>J.advance(s,'finish',{mode:'3d',winner:'trial-ana',seconds:-2,players:['trial-ana','trial-bia']}),/resultado fictício/);
s=J.advance(s,'finish',{mode:'3d',winner:'trial-ana',seconds:48.2,players:['trial-ana','trial-bia']});
assert.equal(s.phase,'finished');assert(Object.isFrozen(s.result));
assert.throws(()=>J.advance(s,'finish',{mode:'3d',winner:'trial-bia',seconds:1,players:['trial-ana','trial-bia']}),/transição inválida/);
s=J.advance(s,'return');assert.equal(s.phase,'returned');
assert.equal(s.result.winner,'trial-ana');
assert.equal(J.advance(s,'invite',{invitationId:2}).result,null);
let text=J.advance(J.advance(J.advance(J.create(),'invite',{invitationId:3}),'accept'),'enter');
text=J.advance(text,'finish',{mode:'text',winner:'trial-bia',seconds:72,players:['trial-ana','trial-bia']});
assert.equal(text.result.mode,'text');
// The invitation contract (not the UI state machine) owns the re-invite lock.
let invites=D.invite(D.createState(),{from,to,context,nowMs:1000,expectedRevision:0});
invites=D.respond(invites,{id:1,actor:'trial-bia',decision:'accept',from,to,context,nowMs:2000,expectedRevision:invites.revision});
assert.throws(()=>D.invite(invites,{from,to,context,nowMs:3000,expectedRevision:invites.revision}),/duelo ativo/);
invites=D.close(invites,{id:1,actor:'trial-ana',nowMs:3000,expectedRevision:invites.revision});
invites=D.invite(invites,{from,to,context,nowMs:4000,expectedRevision:invites.revision});
assert.equal(invites.invitations[1].status,'pending');
console.log('PASS: fictional journey invite/decline/consent/enter/3D/fallback/result/return/reinvite; no XP');
