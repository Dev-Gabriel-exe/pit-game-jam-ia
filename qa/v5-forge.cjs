'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const F=require('../v5/forja-core.js'),P=require('../v5/phase2-combat.js');
for(const klass of F.CLASSES){
 const data=JSON.parse(fs.readFileSync(path.join(__dirname,'../v5/talents-'+klass+'-plan.json'),'utf8'));
 F.verifyCatalog(data);
 assert.equal(data.talents.length,30);
 assert.equal(new Set(data.talents.map(t=>t.tree)).size,3);
 const byPath=[data.talents[0].id,data.talents[10].id,data.talents[20].id,data.talents[5].id,data.talents[15].id];
 let d=F.blank(klass,5);
 byPath.forEach(id=>{d=F.choose(d,id,data)});
 assert.deepEqual(d.talents,byPath,'Three paths must remain freely mixable');
 assert.equal(F.validate(d,data).slotsLeft,0);
 assert.throws(()=>F.choose(d,data.talents[28].id,data),/Todos os talentos/);
 assert.equal(F.executable(d,P.TALENTS[klass].map(t=>t.id),data).ok,true); // B5 all three paths' first talents execute
 d=F.choose(d,byPath[2],data);assert.equal(F.validate(d,data).slotsLeft,1);
 d=F.invest(d,'FOR',1,data);d=F.invest(d,'DES',1,data);
 assert.equal(F.validate(d,data).pointsUsed,2);
 assert.throws(()=>F.invest(d,'FOR',12,data),/Atributo inválido/);
 d=F.setMissions(d,10,data);
 assert.equal(F.budget(d.missions).attributes,20);
 for(let i=0;i<6;i++)d=F.invest(d,'FOR',1,data);
 for(let i=0;i<10;i++)d=F.invest(d,'DEF',1,data);
 assert.equal(F.validate(d,data).pointsUsed,18);
 d=F.setMissions(d,5,data);
 assert(F.validate(d,data).pointsUsed<=10);
 assert(d.talents.length<=5);
 let real=F.blank(klass,5);
 P.TALENTS[klass].slice(0,5).forEach(t=>{real=F.choose(real,t.id,data)});
 assert.equal(F.executable(real,P.TALENTS[klass].map(t=>t.id),data).ok,true);
 assert.equal(F.exportDraft(real,data).serverVerified,false);
 assert.equal(F.exportDraft(real,data).finalLocked,false);
 assert.throws(()=>F.validate({...real,klass:'other'},data),/Rascunho inválido/);
 assert.throws(()=>F.validate({...real,talents:[real.talents[0],real.talents[0]]},data),/inválidos/);
 console.log('FORGE '+klass+': 30 talents, 3 mixed paths, M5/M10 budgets verified');
}
assert.equal(F.CLASSES.length*30,120);
console.log('PASS V5 Forge 120 planned talents selectable, no fabricated server approvals and real M5 battle eligibility');
